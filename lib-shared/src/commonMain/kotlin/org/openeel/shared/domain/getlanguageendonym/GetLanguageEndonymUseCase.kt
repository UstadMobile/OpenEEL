class GetLanguageEndonymUseCase {

    operator fun invoke(langCode: String) : StringResource? {
        val iso6391Code = if(langCode.length >= 2) {
            langCode.substring(0, 2) //Iso639-1 is always a two-letter code
        }else {
            return null
        }

        return resMap[iso6391Code]
    }

