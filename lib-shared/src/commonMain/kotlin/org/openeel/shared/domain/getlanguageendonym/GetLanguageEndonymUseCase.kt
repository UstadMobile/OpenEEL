/**
 * Get the endonym (name of the language in the language itself) for a given ISO 639-1 language code.
 *
 * This is sourced from Wikipedia:
 * https://en.wikipedia.org/wiki/List_of_ISO_639_language_codes
 *
 * Which is copy/pasted into (projectroot)/contrib/language-names.ods which then uses spreadsheet
 * formulas to generate strings.xml resources and mapping.
